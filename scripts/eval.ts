#!/usr/bin/env bun
// Runs every eval case through the real model call, checks the expectations in evals/cases.json and writes
// evals/results.json + evals/RESULTS.md. Commit both: CI (scripts/eval-check.ts) verifies they are current.
// Runs on your own `claude` login, so you pay for your own evals (about US$0.10 per case on the default model).
//
// Usage: bun run eval [--model <id>]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { gradeTranscript, DEFAULT_MODEL } from "../src/grade";
import { cleanTranscript, score } from "../src/lib";
import { AGENT_VERSION, PROMPT_VERSION, parseGrading, rubric } from "../src/portable";
import { type CaseResult, type Results, RESULTS_MD_PATH, RESULTS_PATH, RESULTS_SCHEMA, ROOT, checkCase, fingerprint, loadCases } from "./eval-lib";

const args = process.argv.slice(2);
const i = args.indexOf("--model");
const model = i >= 0 && args[i + 1] ? args[i + 1] : DEFAULT_MODEL;
const cases = loadCases();
if (!cases.allowed_models.includes(model)) console.error(`Note: ${model} is not in allowed_models; CI will reject these results.`);

console.error(`Running ${cases.cases.length} eval cases on ${model}…`);
const results: CaseResult[] = await Promise.all(cases.cases.map(async (c): Promise<CaseResult> => {
  const transcript = cleanTranscript(readFileSync(join(ROOT, c.input), "utf8"));
  const graded = await gradeTranscript(transcript, model, c.id);
  if (!graded.ok) return { id: c.id, critical: c.critical, pass: false, checks: [], error: graded.error, cost_usd: graded.cost };
  const { grading } = parseGrading(graded.raw);
  const s = score(grading!, rubric, transcript);
  const outcome = {
    total: s.total, band: s.band.label,
    levels: Object.fromEntries(s.criteria.map((x) => [x.id, x.level])),
    must_haves: s.criteria.filter((x) => x.must_have).map((x) => x.id),
    flags: s.flags, red_flags: s.red_flags.length,
  };
  const checks = checkCase(c, outcome);
  return { id: c.id, critical: c.critical, pass: checks.every((k) => k.pass), checks, outcome, cost_usd: Math.round(graded.cost * 10000) / 10000 };
}));

const fp = fingerprint(cases);
const failed = results.filter((r) => !r.pass);
const cost = Math.round(results.reduce((a, r) => a + r.cost_usd, 0) * 10000) / 10000;
const out: Results = {
  schema: RESULTS_SCHEMA, fingerprint: fp.hash, fingerprint_files: fp.files, model,
  versions: { agent: AGENT_VERSION, prompt: PROMPT_VERSION, rubric: rubric.rubric_version },
  date: new Date().toISOString().slice(0, 10), cost_usd: cost,
  summary: { cases: results.length, passed: results.length - failed.length, failed: failed.length, critical_failed: failed.filter((r) => r.critical).length },
  cases: results,
};
writeFileSync(RESULTS_PATH, JSON.stringify(out, null, 2) + "\n");

const rows = results.map((r) => `| ${r.id} | ${r.critical ? "yes" : "no"} | ${r.outcome ? `${r.outcome.total} (${r.outcome.band})` : "—"} | ${r.pass ? "pass" : "**FAIL**"} | ${r.error ?? (r.checks.filter((k) => !k.pass).map((k) => `${k.name}: ${k.detail}`).join("; ") || "all checks passed")} |`);
writeFileSync(RESULTS_MD_PATH, `# Eval results

Generated by \`bun run eval\` on ${out.date} · model ${model} · agent v${AGENT_VERSION} · prompt v${PROMPT_VERSION} · rubric v${rubric.rubric_version} · cost US$${cost}

**${out.summary.passed} of ${out.summary.cases} cases passed** · critical failures: ${out.summary.critical_failed}

| Case | Critical | Total | Result | Details |
|------|----------|-------|--------|---------|
${rows.join("\n")}

Fingerprint \`${fp.hash.slice(0, 16)}…\` over ${fp.files} files. CI rejects these results if any of those files change.
`);

console.error(`\n${out.summary.passed}/${out.summary.cases} passed · critical failures ${out.summary.critical_failed} · cost US$${cost}`);
for (const r of failed) console.error(`  FAIL ${r.id}: ${r.error ?? r.checks.filter((k) => !k.pass).map((k) => `${k.name} (${k.detail})`).join("; ")}`);
console.error(`Wrote evals/results.json and evals/RESULTS.md — commit both.`);
process.exit(failed.length ? 1 : 0);
