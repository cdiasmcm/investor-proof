// Builds the portable artifacts from src/portable.ts so non-Bun runtimes get the exact same code:
//   dist/what-are-you-building.js        — one self-contained script; defines globalThis.WhatAreYouBuilding
//   schema/grading.schema.json   — the JSON contract any LLM must return
//   prompt/SYSTEM.md             — prompt that makes an LLM write the finished HTML report (n8n path)
// `bun test` fails if these are stale (src/format.test.ts), so they can't drift from the source.
import { gradingSchema } from "../src/portable";
import { htmlSystemPrompt } from "./html-prompt";

export async function buildBundle(): Promise<string> {
  const out = await Bun.build({ entrypoints: [`${import.meta.dir}/../src/portable-global.ts`], format: "iife", target: "browser", minify: false });
  if (!out.success) throw new Error(out.logs.map(String).join("\n"));
  const code = await out.outputs[0].text();
  return `// What are you building? portable core — generated by scripts/build.ts from src/; do not edit by hand.
// Defines globalThis.WhatAreYouBuilding: systemPrompt(), userPrompt(transcript), gradingSchema(), parseGrading(raw), finalize({grading, transcript, model, source}).
${code}`;
}

export const schemaJson = () => JSON.stringify(gradingSchema(), null, 2) + "\n";

if (import.meta.main) {
  await Bun.write(`${import.meta.dir}/../dist/what-are-you-building.js`, await buildBundle());
  await Bun.write(`${import.meta.dir}/../schema/grading.schema.json`, schemaJson());
  await Bun.write(`${import.meta.dir}/../prompt/SYSTEM.md`, htmlSystemPrompt());
  console.log("built dist/what-are-you-building.js, schema/grading.schema.json and prompt/SYSTEM.md");
}
